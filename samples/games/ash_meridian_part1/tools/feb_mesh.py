# FEB body meshes from the Blender Foundation "Human Base Meshes" bundle (CC0).
# Source: https://mirror.blender.org/demo/asset-bundles/human-base-meshes/human-base-meshes-bundle-v1.0.0.zip
#
# Usage:
#   blender -b human_base_meshes_bundle.blend --python feb_mesh.py -- <out_dir>
#
# Writes figure-space OBJ pieces (Godot axes: +Y up, -Z forward, 1.88 m tall) so the
# rigid pivots in feb.tscn can rotate them without re-offsetting, plus feb_rig.json
# with the pivot positions the scene generator places HeadPivot / arm pivots at.
import bpy, sys, os, json
import numpy as np

out = sys.argv[sys.argv.index('--') + 1]
os.makedirs(out, exist_ok=True)

HEIGHT = 1.88
NECK_Z = 1.56          # Blender units of the source mesh (1.798 m tall)
ARMPIT_Z = 1.30
HELMET_BROW_Z = 1.712
HELMET_BACK_Y = -0.03
HELMET_LIFT = 0.007

src = bpy.data.objects['GEO-body_male_realistic']
for m in src.modifiers:
	if m.type == 'MULTIRES':
		m.levels = 0
dg = bpy.context.evaluated_depsgraph_get()
cx = src.matrix_world.translation.x
scale = HEIGHT / 1.7983


def mesh_arrays(obj):
	ev = obj.evaluated_get(dg)
	me = ev.to_mesh()
	me.calc_loop_triangles()
	M = obj.matrix_world
	R = M.to_3x3().normalized()
	P = np.array([tuple(M @ v.co) for v in me.vertices])
	N = np.array([tuple((R @ v.normal).normalized()) for v in me.vertices])
	T = np.array([tuple(t.vertices) for t in me.loop_triangles])
	return P, N, T


def to_godot(P, N):
	g = np.empty_like(P)
	g[:, 0] = -(P[:, 0] - cx) * scale
	g[:, 1] = P[:, 2] * scale
	g[:, 2] = P[:, 1] * scale
	n = np.empty_like(N)
	n[:, 0] = -N[:, 0]
	n[:, 1] = N[:, 2]
	n[:, 2] = N[:, 1]
	return g, n


def write_obj(path, P, N, T):
	used = np.unique(T)
	remap = -np.ones(len(P), dtype=np.int64)
	remap[used] = np.arange(len(used)) + 1
	with open(path, 'w') as f:
		f.write('# FEB piece generated by tools/feb_mesh.py from CC0 Blender Human Base Meshes\n')
		for p in P[used]:
			f.write('v %.5f %.5f %.5f\n' % tuple(p))
		for n in N[used]:
			f.write('vn %.4f %.4f %.4f\n' % tuple(n))
		for t in T:
			a, b, c = remap[t]
			# X mirror and the Y/Z swap are two reflections, so winding is preserved.
			f.write('f %d//%d %d//%d %d//%d\n' % (a, a, b, b, c, c))
	print('wrote', path, len(used), 'verts', len(T), 'tris')


P, N, T = mesh_arrays(src)
C = P[T].mean(axis=1)
cxz = C.copy()
cxz[:, 0] -= cx
ax = np.abs(cxz[:, 0])
z = cxz[:, 2]

head = z > NECK_Z
shoulder_cut = np.where(z > ARMPIT_Z, 0.18 + 0.3 * (z - ARMPIT_Z), 0.22)
arm = (~head) & (((z > 0.7) & (ax > shoulder_cut)) | ((z > 0.5) & (ax > 0.28)))
# Mesh X is pre-mirror: source -X becomes Godot +X.
arm_pos_godot = arm & (cxz[:, 0] < 0)
arm_neg_godot = arm & (cxz[:, 0] > 0)
body = ~(head | arm)

G, GN = to_godot(P, N)
write_obj(f'{out}/feb_body.obj', G, GN, T[body])
write_obj(f'{out}/feb_head.obj', G, GN, T[head])
write_obj(f'{out}/feb_arm_l.obj', G, GN, T[arm_neg_godot])
write_obj(f'{out}/feb_arm_r.obj', G, GN, T[arm_pos_godot])

# Helmet shell: top and back of the head, lifted along the normal.
hv = np.unique(T[head])
cap_face = head & ((z > HELMET_BROW_Z) | (cxz[:, 1] > HELMET_BACK_Y))
HG = G + GN * HELMET_LIFT
write_obj(f'{out}/feb_helmet.obj', HG, GN, T[cap_face])

eyes = []
for side in ('L', 'R'):
	e = bpy.data.objects[f'GEO-body_male_realistic.eye.{side}']
	EP, EN, ET = mesh_arrays(e)
	EG, EGN = to_godot(EP, EN)
	eyes.append((EG, EGN, ET))
off = len(eyes[0][0])
EG = np.vstack([eyes[0][0], eyes[1][0]])
EGN = np.vstack([eyes[0][1], eyes[1][1]])
ET = np.vstack([eyes[0][2], eyes[1][2] + off])
write_obj(f'{out}/feb_eyes.obj', EG, EGN, ET)


def piece_bounds(mask):
	v = G[np.unique(T[mask])]
	return v.min(axis=0), v.max(axis=0)


rig = {}
rig['height'] = float(G[:, 1].max())
rig['head_pivot'] = [0.0, round(NECK_Z * scale, 4), 0.0]
for name, mask, sign in (('arm_r', arm_pos_godot, 1), ('arm_l', arm_neg_godot, -1)):
	v = G[np.unique(T[mask])]
	top = v[v[:, 1] > v[:, 1].max() - 0.06]
	pivot = [float(np.round(np.median(top[:, 0]), 4)), float(np.round(v[:, 1].max() - 0.06, 4)), float(np.round(np.median(top[:, 2]), 4))]
	low = v[v[:, 1] < v[:, 1].min() + 0.12]
	wrist = v[(v[:, 1] > v[:, 1].min() + 0.16) & (v[:, 1] < v[:, 1].min() + 0.22)]
	rig[name] = {'pivot': pivot, 'wrist': [float(x) for x in np.round(wrist.mean(axis=0), 4)], 'hand': [float(x) for x in np.round(low.mean(axis=0), 4)]}
torso = G[np.unique(T[body])]
band = torso[np.abs(torso[:, 1] - 1.36) < 0.03]
rig['back_z_136'] = float(np.round(band[:, 2].max(), 4))
rig['chest_z_127'] = float(np.round(torso[np.abs(torso[:, 1] - 1.27) < 0.02][:, 2].min(), 4))
with open(f'{out}/feb_rig.json', 'w') as f:
	json.dump(rig, f, indent=1)
print(json.dumps(rig))
